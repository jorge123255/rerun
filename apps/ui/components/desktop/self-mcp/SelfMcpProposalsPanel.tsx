'use client'
import { useCallback, useEffect, useRef, useState } from 'react'
import { toast } from 'sonner'
import type { SelfMcpDecisionRequest, SelfMcpDecisionResult, SelfMcpReviewSnapshot } from '@rerun/contracts'
import { Button } from '@/components/ui/button'
import { EmptyState } from '@/components/ui/empty-state'
import { PanelListHeader, PanelScroller } from '@/components/ui/panel-list'
import { PanelSteps } from '@/components/ui/panel-steps'
import { PlugIcon } from '@/lib/icons'
import { useSelfMcp } from '@/lib/desktop/use-self-mcp'
import { SelfMcpReviewCard } from './SelfMcpReviewCard'
import { SelfMcpReviewEditor } from './SelfMcpReviewEditor'

// Like request ids elsewhere in the desktop UI: the decision id is generated by
// the review client so a retried submit converges to the same result, while the
// server still CAS-reserves the proposal transition (a racing tab loses the CAS
// instead of double-applying).
function newId(): string {
    return typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function'
        ? crypto.randomUUID()
        : `${Date.now()}-${Math.random().toString(36).slice(2)}`
}

export function SelfMcpProposalsPanel({ agentId }: { agentId: string }) {
    return <SelfMcpPanel key={agentId} agentId={agentId} />
}

function SelfMcpPanel({ agentId }: { agentId: string }) {
    const { proposals, pendingId, unavailable, refresh, review, decide, dismiss } = useSelfMcp(agentId)
    const alive = useRef(true)
    const epoch = useRef(0)
    const attempts = useRef(new Map<string, SelfMcpDecisionRequest>())
    const [selectedId, setSelectedId] = useState<string | null>(null)
    const [snapshot, setSnapshot] = useState<SelfMcpReviewSnapshot | null>(null)
    const [busy, setBusy] = useState(false)
    const [error, setError] = useState('')

    useEffect(() => {
        alive.current = true
        return () => {
            alive.current = false
            epoch.current++
        }
    }, [])

    const close = useCallback((refreshAfter = true) => {
        epoch.current++
        setBusy(false)
        setError('')
        setSnapshot(null)
        setSelectedId(null)
        if (refreshAfter) void refresh()
    }, [refresh])

    const open = useCallback(async (proposalId: string) => {
        const myEpoch = ++epoch.current
        setBusy(true)
        setError('')
        setSelectedId(proposalId)
        setSnapshot(null)
        const snapshot = await review(proposalId)
        if (!alive.current || myEpoch !== epoch.current) return
        setBusy(false)
        if (!snapshot) {
            setError('Proposal not found; it may have settled. Refresh the list.')
            setSelectedId(null)
            return
        }
        setSnapshot(snapshot)
    }, [review])

    const decideAndSettle = useCallback(async (outcome: { kind: 'approved' } | { kind: 'rejected'; reason?: string }) => {
        if (!snapshot || busy) return
        const myEpoch = ++epoch.current
        setBusy(true)
        setError('')
        const attemptKey = JSON.stringify([snapshot.proposal.id, snapshot.proposal.revision, snapshot.configRevision, outcome])
        let request = attempts.current.get(attemptKey)
        if (!request) {
            request = {
                proposalId: snapshot.proposal.id,
                decisionId: newId(),
                expectedProposalRevision: snapshot.proposal.revision,
                expectedConfigRevision: snapshot.configRevision,
                outcome,
            }
            attempts.current.set(attemptKey, request)
        }
        const result: SelfMcpDecisionResult | null = await decide(request)
        if (!alive.current || myEpoch !== epoch.current) return
        if (result) {
            if (result.outcome === 'in_flight') {
                setBusy(false)
                setError(result.message)
                return
            }
            if (result.receipt || result.outcome !== 'failed') attempts.current.delete(attemptKey)
            if (result.message) {
                if (result.outcome === 'failed') toast.error(result.message)
                else toast.success(result.message)
            }
        } else {
            setBusy(false)
            setError('The result could not be confirmed. Retry this decision or go back and refresh its status.')
            return
        }
        close()
    }, [snapshot, busy, decide, close])

    const dismissAndSettle = useCallback(async () => {
        if (!snapshot || busy) return
        const myEpoch = ++epoch.current
        setBusy(true)
        setError('')
        const result = await dismiss(snapshot.proposal.id, snapshot.proposal.revision)
        if (!alive.current || myEpoch !== epoch.current) return
        if (result?.message) toast.success(result.message)
        close()
    }, [snapshot, busy, dismiss, close])

    return (
        <PanelSteps stepKey={selectedId ? 'editor' : 'list'} depth={selectedId ? 1 : 0}>
            {selectedId ? (
                snapshot ? (
                    <SelfMcpReviewEditor
                        key={snapshot.proposal.id}
                        snapshot={snapshot}
                        busy={busy || pendingId === selectedId}
                        error={error}
                        onBack={() => close()}
                        onDecide={decideAndSettle}
                        onDismiss={dismissAndSettle}
                    />
                ) : (
                    <div className="p-3 space-y-2">
                        {error && <p role="alert" className="text-xs text-destructive">{error}</p>}
                        <Button size="sm" variant="outline" onClick={() => close()}>Back</Button>
                    </div>
                )
            ) : (
                <div className="flex flex-col h-full">
                    <PanelListHeader count={proposals.length} noun="MCP proposal">
                        <Button size="sm" variant="outline" onClick={() => void refresh()}>Refresh</Button>
                    </PanelListHeader>
                    {error && <p role="alert" className="p-3 text-xs text-destructive">{error}</p>}
                    {unavailable && <p role="alert" className="p-3 text-xs text-destructive">Could not reach the review service; refresh to retry.</p>}
                    {!proposals.length ? (
                        <EmptyState icon={PlugIcon} title="No MCP proposals" description="Proposals appear here when a coworker proposes an MCP server. Nothing is saved or connected until you review it." />
                    ) : (
                        <PanelScroller>
                            {proposals.map(proposal => (
                                <SelfMcpReviewCard
                                    key={proposal.id}
                                    proposal={proposal}
                                    selected={proposal.id === selectedId}
                                    onOpen={() => void open(proposal.id)}
                                />
                            ))}
                        </PanelScroller>
                    )}
                    <p className="p-3 text-xs text-muted-foreground">The model can propose an MCP server but never approve or execute its own proposal. Approval saves it behind the existing MCP and local-program permissions; connection status is shown separately.</p>
                </div>
            )}
        </PanelSteps>
    )
}
