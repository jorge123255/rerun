export function desktopCreationMessages(locale: Locale, source: { dialogs: typeof dialogs; kit: typeof kit }) {
    const dialog = source.dialogs.newAgent
    const composer = source.kit.newAgent
    return {
        ...mac[locale],
        title: dialog.title,
        heading: dialog.heading,
        headingNamed: dialog.headingNamed,
        create: composer.create,
        createCoworker: composer.createCoworker,
        jobLabel: composer.job.label,
        jobPlaceholder: composer.job.placeholder,
        nameLabel: composer.name.label,
        namePlaceholder: composer.name.placeholder,
        close: source.kit.close,
    }
}
