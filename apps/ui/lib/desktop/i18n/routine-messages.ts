type Source = { agent: typeof agent; foreman: typeof foreman; kit: typeof kit; layout: typeof layout }

export function desktopRoutineMessages(locale: Locale, source: Source) {
    const { editor, picker, new: newTask, emptyTitle, emptyDescription, paused } = source.agent.agentPanelScheduled
    return {
        ...mac[locale],
        ...source.foreman.routines,
        coworker: { ...mac[locale].coworker, newTask, emptyTitle, emptyDescription, paused },
        periods: source.kit.foreman.periods,
        labels: source.kit.foreman.routines,
        schedule: source.agent.schedule,
        editor,
        noExecutions: source.agent.agentPanelScheduled.noExecutions,
        modelField: source.agent.runModelField,
        when: picker.when,
        describePlaceholder: picker.describePlaceholder,
        back: source.layout.controlCenter.back,
        timezone: source.agent.timezoneCombobox,
        notifications: source.agent.taskNotifyField,
        status: source.kit.monitoring.runStatus,
        retry: source.kit.chat.skillProposal.retry,
    }
}
